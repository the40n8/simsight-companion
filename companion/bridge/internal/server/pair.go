// sendScript wires the Copy and Share buttons (shown only when they work:
// the page also works without scripts, the link is a plain link).
const sendScript = `(() => {
const link = document.getElementById('link'), said = document.getElementById('said');
const copy = document.getElementById('copy'), share = document.getElementById('share');
if (!link) return;
if (navigator.clipboard) {
  copy.hidden = false;
  copy.onclick = async () => {
    try { await navigator.clipboard.writeText(link.href); said.textContent = 'Link copied.'; }
    catch { said.textContent = 'Could not copy: select the link, then copy it.'; }
  };
}
if (navigator.share) {
  share.hidden = false;
  share.onclick = () => navigator.share({ title: 'SimSight phone link', url: link.href }).catch(() => {});
}
})();`

// pairCSP allows only that script on the page.
var pairCSP = func() string {
	sum := sha256.Sum256([]byte(sendScript))
	return "default-src 'none'; style-src 'unsafe-inline'; img-src data:; script-src 'sha256-" +
		base64.StdEncoding.EncodeToString(sum[:]) + "'; frame-ancestors 'none'; base-uri 'none'; form-action 'none'"
}()

// localOnly accepts requests made on this Mac to 127.0.0.1/localhost, and
// refuses tunnel traffic (which also arrives from loopback, via cloudflared).
func localOnly(r *http.Request) bool {
	host, _, err := net.SplitHostPort(r.RemoteAddr)
	if err != nil || !net.ParseIP(host).IsLoopback() {
		return false
	}
	if r.Header.Get("Cf-Ray") != "" || r.Header.Get("Cf-Connecting-Ip") != "" || r.Header.Get("X-Forwarded-For") != "" {
		return false
	}
	name := r.Host
	if h, _, err := net.SplitHostPort(r.Host); err == nil {
		name = h
	}
	return name == "127.0.0.1" || name == "localhost" || name == "::1"
}

// PairPage shows the phone link as a QR code, on this Mac only (the page
// contains the pairing token).
func PairPage(links LinkFunc, codes *Codes) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		if !localOnly(r) {
			http.NotFound(w, r)
			return
		}
		link, status := links()
		data := struct {
			Link, Status, Note, Spoken string
			SVG                        template.HTML
			Refresh                    bool
		}{Link: link, Status: status}
		if link != "" {
			if svg, err := pairing.SVG(link); err == nil {
				data.SVG = template.HTML(svg) // generated by us: only path data
			}
			// Said aloud when new, or when the page is opened again (not on
			// its own refreshes).
			if codes != nil {
				data.Spoken = SpokenCode(codes.Show(r.URL.Query().Get("again") == ""))
			}
		}
		switch {
		case link == "":
			data.Refresh = true
		case strings.Contains(link, "#m="):
			data.Note = "Meeting point: add the app to the Home Screen once; it finds this " + osutil.Computer() + " by itself each session."
		case strings.Contains(link, "trycloudflare.com"):
			data.Note = "This address changes each game session: scan again next time."
		default:
			data.Note = "Local network link: the phone must be on the same Wi-Fi as this " + osutil.Computer() + "."
		}
		w.Header().Set("Cache-Control", "no-store")
		w.Header().Set("Content-Type", "text/html; charset=utf-8")
		w.Header().Set("Content-Security-Policy", pairCSP)
		w.Header().Set("Referrer-Policy", "no-referrer")
		_ = pairTmpl.Execute(w, data)
	}
}
